# Regenerates src/cloud/trust_anchors.h: the root CAs the terminal trusts for
#   - GitHub firmware updates (always verified), and
#   - the CloudHRM API when CHRM_TLS_MODE is CHRM_TLS_VERIFY.
# Exports common public roots from the Windows root store plus the top of the
# certificate chains that the hosts below serve today.
#   powershell -ExecutionPolicy Bypass -File tools\make_trust_anchors.ps1

$ErrorActionPreference = "Stop"
$out = Join-Path $PSScriptRoot "..\src\cloud\trust_anchors.h"
$hosts = 'login.cloudhrm.in', 'github.com', 'release-assets.githubusercontent.com', 'objects.githubusercontent.com'
$want = 'CN=ISRG Root X1,', 'CN=ISRG Root X2,', 'CN=DigiCert Global Root G2,', 'CN=GTS Root R1,',
        'CN=Amazon Root CA 1,', 'CN=USERTrust RSA Certification Authority,', 'CN=USERTrust ECC Certification Authority,'

$certs = @()
function Add-Cert($c) {
  if ($c -and -not ($script:certs | Where-Object { $_.Thumbprint -eq $c.Thumbprint })) { $script:certs += $c }
}
foreach ($w in $want) {
  $c = Get-ChildItem Cert:\LocalMachine\Root | Where-Object { $_.Subject.StartsWith($w) -and $_.NotAfter -gt (Get-Date) } |
       Sort-Object NotAfter -Descending | Select-Object -First 1
  if ($c) { Add-Cert $c } else { Write-Warning "Not in this PC's root store: $w" }
}

# Certificates above each server's issuing CA in the live chain.
foreach ($h in $hosts) {
  try {
    $tcp = New-Object Net.Sockets.TcpClient($h, 443)
    $ssl = New-Object Net.Security.SslStream($tcp.GetStream(), $false, ([Net.Security.RemoteCertificateValidationCallback] { $true }))
    $ssl.AuthenticateAsClient($h)
    $leaf = New-Object Security.Cryptography.X509Certificates.X509Certificate2($ssl.RemoteCertificate)
    $chain = New-Object Security.Cryptography.X509Certificates.X509Chain
    [void]$chain.Build($leaf)
    $ssl.Dispose(); $tcp.Close()
    $elements = @($chain.ChainElements | ForEach-Object { $_.Certificate })
    if ($elements.Count -gt 2) { foreach ($c in $elements[2..($elements.Count - 1)]) { Add-Cert $c } }
  } catch {
    Write-Warning "Could not read the chain of ${h}: $($_.Exception.Message)"
  }
}

$sb = New-Object Text.StringBuilder
[void]$sb.AppendLine('// Root CAs for GitHub firmware updates and the optional CloudHRM TLS verify mode.')
[void]$sb.AppendLine('// Generated by tools/make_trust_anchors.ps1 on ' + (Get-Date -Format 'yyyy-MM-dd') + '. Do not edit by hand.')
[void]$sb.AppendLine('#pragma once')
[void]$sb.AppendLine('#include <Arduino.h>')
[void]$sb.AppendLine('')
[void]$sb.AppendLine('static const char TRUST_ANCHORS_PEM[] PROGMEM = R"PEM(')
foreach ($c in $certs) {
  [void]$sb.AppendLine('# ' + $c.Subject.Split(',')[0] + '  (expires ' + $c.NotAfter.ToString('yyyy-MM-dd') + ')')
  [void]$sb.AppendLine('-----BEGIN CERTIFICATE-----')
  [void]$sb.AppendLine([Convert]::ToBase64String($c.RawData, 'InsertLineBreaks'))
  [void]$sb.AppendLine('-----END CERTIFICATE-----')
}
[void]$sb.AppendLine(')PEM";')
$sb.ToString().Replace("`r`n", "`n") | Set-Content -Encoding utf8 -NoNewline $out
$certs | ForEach-Object { "{0}  (expires {1:yyyy-MM-dd})" -f $_.Subject.Split(',')[0], $_.NotAfter }
