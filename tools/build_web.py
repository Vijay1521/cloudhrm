"""Pack web/index.html into src/web/portal_html.h (gzipped, PROGMEM).

Run after every change to the web page:
    python tools/build_web.py
"""
import gzip
import pathlib

ROOT = pathlib.Path(__file__).resolve().parent.parent
SRC = ROOT / "web" / "index.html"
OUT = ROOT / "src" / "web" / "portal_html.h"


def minify(html: str) -> str:
    # Conservative: drop indentation and blank lines only. Safe for the inline
    # CSS and JS because neither relies on leading whitespace.
    lines = (line.strip() for line in html.splitlines())
    return "\n".join(line for line in lines if line)


def main() -> None:
    raw = SRC.read_text(encoding="utf-8")
    data = gzip.compress(minify(raw).encode("utf-8"), compresslevel=9, mtime=0)
    rows = []
    for i in range(0, len(data), 20):
        rows.append("  " + ", ".join(f"0x{b:02x}" for b in data[i:i + 20]) + ",")
    OUT.write_text(
        "// Generated by tools/build_web.py from web/index.html. Do not edit.\n"
        "#pragma once\n"
        "#include <Arduino.h>\n\n"
        f"// {len(raw)} bytes of HTML, {len(data)} bytes gzipped.\n"
        f"static const size_t PORTAL_HTML_GZ_LEN = {len(data)};\n"
        "static const uint8_t PORTAL_HTML_GZ[] PROGMEM = {\n" + "\n".join(rows) + "\n};\n",
        encoding="utf-8",
    )
    print(f"{SRC.name}: {len(raw)} bytes -> {len(data)} bytes gzipped -> {OUT.relative_to(ROOT)}")


if __name__ == "__main__":
    main()
